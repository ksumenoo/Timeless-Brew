def H1(text):   # «Раздел N»
    p = d.add_paragraph(); r = p.add_run(text); r.bold = True; r.font.size = Pt(16)
    pf = p.paragraph_format; pf.page_break_before = True; pf.space_before = Pt(12); pf.space_after = Pt(12)
    return p

def H2(text):   # подраздел «7.1», «6.18. …»
    p = d.add_paragraph(); r = p.add_run(text); r.bold = True; r.font.size = Pt(14)
    pf = p.paragraph_format; pf.keep_with_next = True; pf.space_before = Pt(16); pf.space_after = Pt(9)
    return p

def illus(text):   # подпись-иллюстрация (по центру, мельче)
    p = d.add_paragraph(); r = p.add_run(text); r.font.size = Pt(11)
    pf = p.paragraph_format; pf.alignment = AL.CENTER; pf.space_before = Pt(3); pf.space_after = Pt(12)
    return p

def body(text):   # обычный абзац: по ширине, отступ первой строки
    p = d.add_paragraph(); p.add_run(text)
    pf = p.paragraph_format; pf.first_line_indent = Pt(28.35); pf.alignment = AL.JUSTIFY
    return p

def label(lbl, text):   # «Описание. …» — полужирная метка + обычный текст
    p = d.add_paragraph(); rb = p.add_run(lbl + ' '); rb.bold = True; p.add_run(text)
    pf = p.paragraph_format; pf.first_line_indent = Pt(28.35); pf.alignment = AL.JUSTIFY
    return p

def bullet(text):   # «—  …» с висячим отступом
    p = d.add_paragraph(); p.add_run('—  ' + text)
    pf = p.paragraph_format; pf.left_indent = Pt(28.35); pf.first_line_indent = Pt(-14.15); pf.space_after = Pt(3)
    return p


def find(prefix):
    for p in d.paragraphs:
        if p.text.strip().startswith(prefix):
            return p
    return None

