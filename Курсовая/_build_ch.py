def toc_clone_insert(doc, entries):
    # Ищем строки ИМЕННО оглавления (стиль Normal, до заголовка ВВЕДЕНИЕ), а не сами заголовки глав.
    from docx.oxml import OxmlElement
    XMLSPACE = '{http://www.w3.org/XML/1998/namespace}space'
    paras = doc.paragraphs
    intro_idx = next((i for i, p in enumerate(paras)
                      if p.style.name == 'Heading 1' and p.text.strip().startswith('ВВЕДЕНИЕ')), len(paras))
    region = paras[:intro_idx]

    def first(pred):
        return next((p for p in region if pred(p)), None)

    anchor = first(lambda p: p.style.name == 'Normal' and p.text.strip().startswith('2.6.'))
    tmpl_ind = first(lambda p: p.style.name == 'Normal' and p.text.strip().startswith('2.1.'))
    tmpl_noind = first(lambda p: p.style.name == 'Normal' and p.text.strip().startswith('ГЛАВА 2.'))
    if anchor is None or tmpl_ind is None or tmpl_noind is None:
        print('TOC: шаблоны оглавления не найдены — пропуск обновления содержания')
        return
    prev = anchor._p
    for text, indented in entries:
        tmpl = tmpl_ind if indented else tmpl_noind
        new = copy.deepcopy(tmpl._p)
        # Сносим все прогоны шаблона и вставляем один чистый прогон с нужным текстом (pPr с табами/отступом сохраняется).
        for r in new.findall(qn('w:r')):
            new.remove(r)
        r = OxmlElement('w:r'); t = OxmlElement('w:t')
        t.set(XMLSPACE, 'preserve'); t.text = text
        r.append(t)
        pPr = new.find(qn('w:pPr'))
        if pPr is not None:
            pPr.addnext(r)
        else:
            new.append(r)
        prev.addnext(new)
        prev = new


