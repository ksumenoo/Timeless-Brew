# ---------- построители абзацев (в стиле документа) ----------
def H1(text):   # «Раздел N»
    p = d.add_paragraph(); r = p.add_run(text); r.bold = True; r.font.size = Pt(16)
    pf = p.paragraph_format; pf.page_break_before = True; pf.space_before = Pt(12); pf.space_after = Pt(12)
    return p

def H2(text):   # «3.1», «4.1» …
    p = d.add_paragraph(); r = p.add_run(text); r.bold = True; r.font.size = Pt(14)
    pf = p.paragraph_format; pf.keep_with_next = True; pf.space_before = Pt(16); pf.space_after = Pt(9)
    return p

def H3(text):   # «Этап N …»
    p = d.add_paragraph(); r = p.add_run(text); r.bold = True; r.font.size = Pt(13)
    pf = p.paragraph_format; pf.keep_with_next = True; pf.space_before = Pt(10); pf.space_after = Pt(6)
    return p

def body(text):
    p = d.add_paragraph(); p.add_run(text)
    pf = p.paragraph_format; pf.first_line_indent = Pt(28.35); pf.alignment = AL.JUSTIFY
    return p

def label(lbl, text):
    p = d.add_paragraph(); rb = p.add_run(lbl + ' '); rb.bold = True; p.add_run(text)
    pf = p.paragraph_format; pf.first_line_indent = Pt(28.35); pf.alignment = AL.JUSTIFY
    return p

def bullet(text):
    p = d.add_paragraph(); p.add_run('—  ' + text)
    pf = p.paragraph_format; pf.left_indent = Pt(28.35); pf.first_line_indent = Pt(-14.15); pf.space_after = Pt(3)
    return p


def find(prefix):
    for p in d.paragraphs:
        if p.text.strip().startswith(prefix):
            return p
    raise SystemExit('Не найден абзац: ' + prefix)

def del_range(start_el, end_el):   # удалить [start_el, end_el)
    el = start_el; rm = []
    while el is not None and el is not end_el:
        rm.append(el); el = el.getnext()
    for e in rm:
        e.getparent().remove(e)

def has_drawing(el):
    return bool(el.findall('.//' + qn('w:drawing')) or el.findall('.//' + qn('a:blip')) or el.findall('.//' + qn('w:pict')))


