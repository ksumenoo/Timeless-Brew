namespace TimelessBrew.Day
{
    /// <summary>
    /// Фазы одного игрового дня (§4.4). Прототип охватывает ровно один день,
    /// разделённый на утро, день и вечер. Один и тот же гость может зайти
    /// дважды — утром и вечером — с разными заказами.
    ///
    /// Closed идёт после вечера: день завершён, новые гости не приходят.
    /// </summary>
    public enum DayPhase
    {
        Morning,
        Day,
        Evening,
        Closed
    }
}
