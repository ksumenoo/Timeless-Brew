namespace TimelessBrew.Audio
{
    /// <summary>
    /// Звуковые события игры. Имена слагов (см. <see cref="SoundLibrary"/>) совпадают с файлами
    /// в Resources/Audio/SFX. Набор соответствует фактическим озвученным файлам из папки Sounds:
    /// озвучка идёт «по объектам» — взять/поставить у каждого предмета свой звук.
    /// Часть событий пока без файла (мехи, пережар, сироп, листание) — играют тишину, см. примечания.
    /// </summary>
    public enum Sfx
    {
        None = 0,

        // Взять/поставить — по объектам (файл «Взять или поставить …» = и взятие, и постановка).
        TakePlaceMilk,      // бутылка молока (и взятие из холодильника)
        TakePlacePan,       // сковорода
        TakePlaceBeanJar,   // банка с зёрнами
        PlaceKettle,        // поставить чайник
        PlaceCupSaucer,     // поставить чашку/блюдце (и как «посуда на посуду»)
        PlaceTray,          // поставить поднос

        // Наливы и сыпь — длинные (loop, пока удерживаем).
        PourBeans,          // сыпать зёрна (банка→сковорода/дуршлаг)
        PourWater,          // лить воду из чайника в турку
        PourCoffee,         // лить готовый кофе из турки в чашку
        PourMilk,           // лить молоко (баночка→питчер→чашка)

        // Печь / сковорода.
        RoastSizzle,        // обжарка зёрен на огне (loop)
        Overheat,           // печь раскалилась до предела

        // Кофемолка.
        Grind,              // помол зёрен (loop)
        GrindEmpty,         // кофемолка крутится вхолостую (loop)

        // Чайник / турка.
        KettleBoil,         // свист закипающего чайника (loop)
        CezveBrew,          // бурление кофе в турке (loop)
        SpoonStir,          // работа ложки в турке (loop)

        // Раковина / дуршлаг.
        SinkFill,           // набрать воды из крана
        Sift,               // просеивание дуршлагом (loop)
        BeansInColander,    // зёрна пересыпали в дуршлаг

        // Добавки.
        Spice,              // насыпать специю
        SugarCube,          // кубик сахара в чашку
        SugarOpen,          // достать сахар из сахарницы
        Syrup,              // налить сироп в чашку (пока плейсхолдер — звук налива, заменяемо)

        // Сервис / мусор.
        Trash,              // выкинуть в мусорку
        BellServe,          // звоночек выдачи
        GuestCall,          // приход гостя

        // Резерв (для будущих экранов).
        RoastModeSwitch     // смена режима между обжарками (для блокнота обжарки)
    }

    /// <summary>Музыка и длинные эмбиенты (Resources/Audio/Music).</summary>
    public enum Music
    {
        None = 0,
        Menu,               // главное меню
        Gameplay,           // фон рабочего дня в кофейне
        EveningAmbience,    // вечерний эмбиент (для смены времени суток)
        Endshift,           // подведение итогов смены
        NatureLoop          // эмбиент леса/природы
    }
}
