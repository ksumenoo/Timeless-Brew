using System;
using UnityEngine;

namespace TimelessBrew.Data
{
    /// <summary>
    /// Фактически приготовленный напиток — то, что собрал игрок за пять этапов готовки (§4.2).
    /// В отличие от <see cref="DrinkSpec"/> (категориальный «что хотели»), здесь хранятся
    /// ОБА слоя информации:
    ///   • <see cref="spec"/> — категориальные выборы игрока (помол, вода, молоко, сахар, сироп,
    ///     специи) и итоговая степень обжарки — то, что сравнивается с заказом гостя;
    ///   • качество выполнения тактильных мини-игр (0..1) — насколько чисто сделан каждый этап.
    ///
    /// Итоговый балл §4.3 = насколько совпало с заказом × насколько чисто выполнено.
    /// Значение -1 у качества = этап не выполнялся (нет данных) и в оценке трактуется
    /// как нейтральное (множитель 1), чтобы отладочные подачи без готовки работали.
    /// </summary>
    [Serializable]
    public class BrewResult
    {
        [Tooltip("Категориальный состав собранного напитка (сравнивается с заказом).")]
        public DrinkSpec spec = new();

        [Header("Качество выполнения этапов (0..1; -1 = этап не выполнялся)")]
        [Tooltip("Этап 1 — обжарка: попал ли в окно прожарки (RoastingPan.RoastQuality01).")]
        [Range(-1f, 1f)] public float roastQuality = -1f;

        [Tooltip("Этап 2 — просеивание шелухи: чистота зерна. Пропуск этапа снижает оценку (§4.2).")]
        [Range(-1f, 1f)] public float siftQuality = -1f;

        [Tooltip("Этап 3 — варка: пенка не перелита, режим выдержан.")]
        [Range(-1f, 1f)] public float brewQuality = -1f;

        [Tooltip("Этап 5 — латте-арт: чёткость рисунка (только для напитков с молоком).")]
        [Range(-1f, 1f)] public float latteArtQuality = -1f;

        /// <summary>Обернуть готовый DrinkSpec без данных о качестве (для отладки/обратной совместимости).</summary>
        public static BrewResult FromSpec(DrinkSpec spec)
        {
            return new BrewResult { spec = spec ?? new DrinkSpec() };
        }
    }
}
